void ssd1306DrawFrame(const uint8_t *frame)
{
    memcpy(
        ssd1306_buffer,
        frame,
        SSD1306_WIDTH * SSD1306_HEIGHT / 8
    );
}

void ssd1306Video(void) {
    //badapple
    /*
    * 정확히 1024바이트 수신 완료
    */
    if (frame_ready) {
        frame_ready = 0;
        /*
        * UART DMA로 받은 프레임을
        * SSD1306 화면 버퍼로 복사
        */
        ssd1306DrawFrame(frame_buf);
        
        /*
        * OLED에 실제 출력
        */
        ssd1306Update();
        
        /*
        * Python에게
        * "이 프레임 출력 끝났음"
        * ACK 전송
        */
    uint8_t ack = 'A';
    HAL_UART_Transmit( &huart2, &ack,1, 100 );

    /*
    * 다음 프레임 1024바이트 DMA 수신 시작
    */
    HAL_UART_Receive_DMA( &huart2, frame_buf, FRAME_SIZE );
    }
}

